"""Heartbeat-backed presence for active Revora browser tabs.

Presence is intentionally ephemeral and advisory. It never authenticates a
request and never starts a kLLM unload. It only answers "is there a recently
active, authenticated browser tab?" so automatic loading can be suppressed when
nobody is using Revora.
"""

from __future__ import annotations

import hashlib
import uuid
from datetime import UTC, datetime, timedelta
from typing import Any

from sqlalchemy import delete, func, or_, select
from sqlalchemy.exc import IntegrityError
from sqlalchemy.ext.asyncio import AsyncSession

from app.models.user_presence import UserPresence

#: A heartbeat is considered live for this long. The browser sends one every
#: 30 seconds while visible and recently interactive.
ACTIVE_TTL_SECONDS = 120
#: Keep old rows long enough for debugging/auditing, then prune opportunistically.
RETENTION_DAYS = 1


def normalize_client_session_id(raw: str | None) -> str:
    """Validate the per-tab UUID generated by the browser."""
    if not isinstance(raw, str) or not raw.strip():
        raise ValueError("A browser session identifier is required.")
    try:
        return str(uuid.UUID(raw.strip()))
    except (ValueError, AttributeError) as exc:
        raise ValueError("The browser session identifier is invalid.") from exc


def hash_token_jti(jti: Any) -> str:
    """One-way fingerprint for a login token; never store the raw jti."""
    value = str(jti or "").strip()
    if not value:
        raise ValueError("The session token has no identity.")
    return hashlib.sha256(value.encode("utf-8")).hexdigest()


def _as_utc(value: datetime | None) -> datetime | None:
    if value is None:
        return None
    if value.tzinfo is None:
        return value.replace(tzinfo=UTC)
    return value.astimezone(UTC)


def _token_expiry(payload: dict[str, Any], now: datetime) -> datetime:
    try:
        exp = int(payload.get("exp", 0) or 0)
    except (TypeError, ValueError):
        exp = 0
    if exp <= 0:
        raise ValueError("The session token has no expiry.")
    return datetime.fromtimestamp(exp, tz=UTC)


def public_status(
    row: UserPresence | None, *, now: datetime | None = None
) -> dict[str, Any]:
    """Sanitized presence projection. No user id or session identifier leaks."""
    now = now or datetime.now(UTC)
    if row is None:
        return {
            "active": False,
            "last_seen_at": None,
            "expires_at": None,
        }
    last_seen = _as_utc(row.last_seen_at)
    expires = _as_utc(row.expires_at)
    active = bool(
        row.active
        and last_seen is not None
        and expires is not None
        and expires > now
        and now - last_seen <= timedelta(seconds=ACTIVE_TTL_SECONDS)
    )
    return {
        "active": active,
        "last_seen_at": last_seen.isoformat() if last_seen else None,
        "expires_at": expires.isoformat() if expires else None,
    }


async def upsert_heartbeat(
    db: AsyncSession,
    *,
    user_id: uuid.UUID,
    payload: dict[str, Any],
    client_session_id: str,
    active: bool,
    now: datetime | None = None,
) -> UserPresence:
    """Create or refresh one browser-tab presence row."""
    now = now or datetime.now(UTC)
    session_id = normalize_client_session_id(client_session_id)
    jti_hash = hash_token_jti(payload.get("jti"))
    expires_at = _token_expiry(payload, now)
    if active and expires_at <= now:
        active = False

    result = await db.execute(
        select(UserPresence).where(
            UserPresence.user_id == user_id,
            UserPresence.client_session_id == session_id,
        )
    )
    row = result.scalars().first()
    if row is None:
        row = UserPresence(
            user_id=user_id,
            client_session_id=session_id,
            token_jti_hash=jti_hash,
            active=active,
            last_seen_at=now,
            expires_at=expires_at,
            ended_at=None if active else now,
        )
        db.add(row)
        try:
            async with db.begin_nested():
                await db.flush()
        except IntegrityError:
            # Another request created the same tab row concurrently. Reload and
            # update that row instead of failing the heartbeat.
            await db.rollback()
            result = await db.execute(
                select(UserPresence).where(
                    UserPresence.user_id == user_id,
                    UserPresence.client_session_id == session_id,
                )
            )
            row = result.scalars().first()
            if row is None:
                raise
    if row is not None:
        row.token_jti_hash = jti_hash
        row.active = bool(active)
        row.last_seen_at = now
        row.expires_at = expires_at
        row.ended_at = None if active else now
        db.add(row)
    return row


async def deactivate(
    db: AsyncSession,
    *,
    user_id: uuid.UUID,
    client_session_id: str,
    now: datetime | None = None,
) -> UserPresence | None:
    """Mark one browser tab inactive. Never issues a kLLM lifecycle action."""
    now = now or datetime.now(UTC)
    session_id = normalize_client_session_id(client_session_id)
    result = await db.execute(
        select(UserPresence).where(
            UserPresence.user_id == user_id,
            UserPresence.client_session_id == session_id,
        )
    )
    row = result.scalars().first()
    if row is not None:
        row.active = False
        row.last_seen_at = now
        row.ended_at = now
        db.add(row)
    return row


async def get_status(
    db: AsyncSession,
    *,
    user_id: uuid.UUID,
    client_session_id: str,
    now: datetime | None = None,
) -> dict[str, Any]:
    now = now or datetime.now(UTC)
    session_id = normalize_client_session_id(client_session_id)
    result = await db.execute(
        select(UserPresence).where(
            UserPresence.user_id == user_id,
            UserPresence.client_session_id == session_id,
        )
    )
    return public_status(result.scalars().first(), now=now)


async def has_active_session(
    db: AsyncSession, *, now: datetime | None = None
) -> bool:
    """True when at least one valid, recently refreshed browser tab exists."""
    now = now or datetime.now(UTC)
    cutoff = now - timedelta(seconds=ACTIVE_TTL_SECONDS)
    result = await db.execute(
        select(func.count())
        .select_from(UserPresence)
        .where(UserPresence.active.is_(True))
        .where(UserPresence.last_seen_at >= cutoff)
        .where(UserPresence.expires_at > now)
    )
    return int(result.scalar() or 0) > 0


async def count_active_sessions(
    db: AsyncSession, *, now: datetime | None = None
) -> int:
    now = now or datetime.now(UTC)
    cutoff = now - timedelta(seconds=ACTIVE_TTL_SECONDS)
    result = await db.execute(
        select(func.count())
        .select_from(UserPresence)
        .where(UserPresence.active.is_(True))
        .where(UserPresence.last_seen_at >= cutoff)
        .where(UserPresence.expires_at > now)
    )
    return int(result.scalar() or 0)


async def prune_expired(
    db: AsyncSession, *, now: datetime | None = None
) -> int:
    """Remove old rows opportunistically. No background scheduler is required."""
    now = now or datetime.now(UTC)
    cutoff = now - timedelta(days=RETENTION_DAYS)
    # Use the Core table for the bulk delete: SQLAlchemy's ORM evaluator
    # compares in-memory timezone-aware values against SQLite's naive round-trip.
    result = await db.execute(
        delete(UserPresence.__table__).where(
            or_(
                UserPresence.__table__.c.expires_at < cutoff,
                UserPresence.__table__.c.ended_at < cutoff,
            )
        )
    )
    return int(result.rowcount or 0)


async def delete_all_for_user(db: AsyncSession, user_id: uuid.UUID) -> int:
    """Explicit logout revokes every login, so all of that user's tabs end."""
    result = await db.execute(
        delete(UserPresence.__table__).where(
            UserPresence.__table__.c.user_id == user_id
        )
    )
    return int(result.rowcount or 0)
